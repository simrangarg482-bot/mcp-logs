"""These shared Pydantic schemas define the standard output formats for 
`agents.answer_question` and `agents.triage_incident`, so `agents/`, `api/`, `mcp/`, 
and `core/incidents` all use the same data structure. They live in `shared/` because 
multiple modules need them, rather than belonging to just one module. 
"""

from __future__ import annotations

import uuid
from datetime import datetime
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field


class Citation(BaseModel):
    """One grounded reference backing a sentence in `AskResponse.answer` --
    API_DESIGN.md's contract for making the Answer Agent's grounding
    verifiable rather than asserted.
    """

    model_config = ConfigDict(frozen=True)

    document_id: uuid.UUID
    chunk_id: uuid.UUID
    source_url: str | None
    excerpt: str


class EvidenceItem(BaseModel):
    """`EvidenceItem` represents one piece of verified evidence retrieved from a source,
     rather than content generated by the AI. Its `source` identifies where the evidence
     came from, such as a GitHub issue, commit, monitoring system, runbook, or postmortem
     . `source_timestamp` records when the original event occurred, while `metadata` 
     stores structured details like authors, labels, or changed files. These optional 
     fields preserve compatibility with existing code, and the structured evidence can 
     also be saved to `incident_timeline` for later use.
    """

    model_config = ConfigDict(frozen=True)

    source: Literal[
        "github",
        "pull_request",
        "commit",
        "issue",
        "slack",
        "jira",
        "deployment",
        "postmortem",
        "monitoring",
        "runbook",
    ]
    reference: str  # PR number, message link, ticket ID, etc.
    summary: str
    retrieved_at: datetime
    source_timestamp: datetime | None = None
    metadata: dict[str, str] = Field(default_factory=dict)


class RootCauseHypothesis(BaseModel):
    """One AI-generated hypothesis from the Investigation Agent's sub-stage
    B. `supporting_evidence_ids` must reference real `EvidenceItem.reference` values 
    from the same investigation -- a hypothesis with none is rejected by a validation
    step and never surfaced never constructed here without at least one entry.
    """

    model_config = ConfigDict(frozen=True)

    description: str
    confidence: float
    supporting_evidence_ids: list[str]


class InvestigationResult(BaseModel):
    """`InvestigationResult` is included in `AskResponse` only when the system chooses 
    the investigation route. It keeps verified evidence (`evidence`) separate from 
    AI-generated explanations (`hypotheses`). The critique-related fields track whether 
    the hypotheses were reviewed, the critique verdict, revision count, and any issue 
    tags. Consumers must check `review_status` before treating hypotheses as reviewed: 
    `reviewed` means critique completed, `not_reviewed` means it did not run, and 
    `review_failed` means it was attempted but failed.
    """

    model_config = ConfigDict(frozen=True)

    evidence: list[EvidenceItem]
    hypotheses: list[RootCauseHypothesis]
    suggested_owner_team: str | None
    suggested_next_steps: list[str]
    review_status: Literal["not_reviewed", "reviewed", "review_failed"] = "not_reviewed"
    critique_verdict: Literal["accept", "revise", "reject"] | None = None
    revision_count: int = 0
    critique_issues: list[str] = Field(default_factory=list)


class AskResponse(BaseModel):
    """`AskResponse` is the result returned after EKIP processes a question. It contains
      either an answer or an investigation, depending on what the system decides to do. 
      The `answer_mode` field tells us whether EKIP successfully gave an answer 
      (`"answered"`) or refused because it didn't have enough reliable information 
      (`"no_answer"`). If the system was investigating or something technically failed,
      `answer_mode` stays `None` because EKIP hasn't made a normal answer-or-refusal 
      decision.
    """

    model_config = ConfigDict(frozen=True)

    confidence: float
    route_taken: Literal["answer", "investigation"]
    answer: str | None = None
    answer_mode: Literal["answered", "no_answer"] | None = None
    citations: list[Citation] = Field(default_factory=list)
    investigation: InvestigationResult | None = None


class GapReport(BaseModel):
    """One recommendation produced by the Knowledge Gap Agent.

    Mirrors `app.database.models.agent_models.KnowledgeGapReport`'s columns
    `supporting_execution_ids` references
    `AgentExecution.id` values, not a persisted evidence-item shape --
    fetching the underlying executions is a separate lookup a reviewer's
    tooling can do if it wants the actual query text back.
    """

    model_config = ConfigDict(frozen=True)

    id: uuid.UUID
    organization_id: uuid.UUID
    suggested_topic: str
    supporting_execution_ids: list[uuid.UUID]
    suggested_action: Literal["new_runbook", "update_existing"]
    related_document_id: uuid.UUID | None
    status: Literal["open", "dismissed"]
    created_at: datetime
    updated_at: datetime
